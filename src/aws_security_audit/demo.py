DEMO_REGIONS = ("eu-west-2", "us-east-1")
MOCK_ACCOUNT_ID = "123456789012"
DEMO_NOTE = (
    f"Generated by 'aws-security-audit demo' against a moto mock account ({MOCK_ACCOUNT_ID}). "
    "This is not a real AWS account and no real AWS API calls were made."
)

# Fake credentials only. The real environment's AWS settings are removed
# for the duration of the demo and put back afterwards.
FAKE_ENV = {
    "AWS_ACCESS_KEY_ID": "testing",
    "AWS_SECRET_ACCESS_KEY": "testing",
    "AWS_SESSION_TOKEN": "testing",
    "AWS_DEFAULT_REGION": "us-east-1",
    "AWS_CONFIG_FILE": os.devnull,
    "AWS_SHARED_CREDENTIALS_FILE": os.devnull,
    "AWS_EC2_METADATA_DISABLED": "true",
    "MOTO_EC2_LOAD_DEFAULT_AMIS": "false",
}

ALL_ON = {"BlockPublicAcls": True, "IgnorePublicAcls": True, "BlockPublicPolicy": True, "RestrictPublicBuckets": True}
STAR_POLICY = {"Version": "2012-10-17", "Statement": [{"Effect": "Allow", "Action": "*", "Resource": "*"}]}


class DemoUnavailable(RuntimeError):
    pass


@contextmanager
def mocked_aws() -> Iterator[None]:
    try:
        from moto import mock_aws
    except ImportError:
        raise DemoUnavailable(
            "the demo needs moto, which is a dev dependency: pip install -r requirements-dev.txt"
        ) from None
    saved = {k: v for k, v in os.environ.items() if k.startswith(("AWS_", "MOTO_"))}
    for key in saved:
        del os.environ[key]
    os.environ.update(FAKE_ENV)
    try:
        with mock_aws():
            yield
    finally:
        for key in FAKE_ENV:
            os.environ.pop(key, None)
        os.environ.update(saved)


def _bucket(name: str, region: str):
    s3 = boto3.client("s3", region_name=region)
    if region == "us-east-1":
        s3.create_bucket(Bucket=name)
    else:
        s3.create_bucket(Bucket=name, CreateBucketConfiguration={"LocationConstraint": region})
    return s3


def _default_encryption(algorithm: str) -> dict:
    return {"Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": algorithm}}]}


def build_misconfigured_account() -> list[str]:
    """Create the demo resources. Returns a plain description of what was planted."""
    planted: list[str] = []

    # --- IAM -----------------------------------------------------------------------
    iam = boto3.client("iam")
    iam.update_account_password_policy(MinimumPasswordLength=8)
    planted.append("Password policy with an 8 character minimum and no reuse prevention")

    iam.create_user(UserName="deploy-bot")
    iam.create_access_key(UserName="deploy-bot")
    policy = iam.create_policy(PolicyName="ci-deploy-everything", PolicyDocument=json.dumps(STAR_POLICY))
    iam.attach_user_policy(UserName="deploy-bot", PolicyArn=policy["Policy"]["Arn"])
    planted.append("User deploy-bot with an access key and a customer managed '*:*' policy")

    iam.create_user(UserName="alice")
    iam.create_login_profile(UserName="alice", Password="Demo-only-password-1")
    read_policy = {
        "Version": "2012-10-17",
        "Statement": [{"Effect": "Allow", "Action": "s3:GetObject", "Resource": "arn:aws:s3:::demo-app-data/*"}],
    }
    iam.put_user_policy(UserName="alice", PolicyName="read-app-data", PolicyDocument=json.dumps(read_policy))
    planted.append("User alice with a console password and no MFA")

    iam.create_user(UserName="bob")
    iam.create_login_profile(UserName="bob", Password="Demo-only-password-2")
    serial = iam.create_virtual_mfa_device(VirtualMFADeviceName="bob")["VirtualMFADevice"]["SerialNumber"]
    iam.enable_mfa_device(
        UserName="bob", SerialNumber=serial, AuthenticationCode1="123456", AuthenticationCode2="654321"
    )
    planted.append("User bob with a console password and MFA (should pass)")

    # --- S3 --------------------------------------------------------------------------
    s3 = _bucket("demo-public-assets", "us-east-1")
    public = {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Sid": "PublicRead",
                "Effect": "Allow",
                "Principal": "*",
                "Action": "s3:GetObject",
                "Resource": "arn:aws:s3:::demo-public-assets/*",
            }
        ],
    }
    s3.put_bucket_policy(Bucket="demo-public-assets", Policy=json.dumps(public))
    planted.append("Bucket demo-public-assets with a Principal '*' bucket policy and no public access block")

    _bucket("demo-customer-exports", "eu-west-2")
    planted.append("Bucket demo-customer-exports (London) with no public access block, versioning or logging")

    logs = _bucket("demo-access-logs", "us-east-1")
    log_delivery = {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Effect": "Allow",
                "Principal": {"Service": "logging.s3.amazonaws.com"},
                "Action": "s3:PutObject",
                "Resource": "arn:aws:s3:::demo-access-logs/*",
            }
        ],
    }
    logs.put_bucket_policy(Bucket="demo-access-logs", Policy=json.dumps(log_delivery))
    logs.put_public_access_block(Bucket="demo-access-logs", PublicAccessBlockConfiguration=ALL_ON)
    logs.put_bucket_versioning(Bucket="demo-access-logs", VersioningConfiguration={"Status": "Enabled"})
    logs.put_bucket_encryption(
        Bucket="demo-access-logs",
        ServerSideEncryptionConfiguration=_default_encryption("AES256"),
    )
    planted.append("Bucket demo-access-logs: locked down, but no logging of its own (suppressed in the demo)")

    data = _bucket("demo-app-data", "us-east-1")
    data.put_public_access_block(Bucket="demo-app-data", PublicAccessBlockConfiguration=ALL_ON)
    data.put_bucket_versioning(Bucket="demo-app-data", VersioningConfiguration={"Status": "Enabled"})
    data.put_bucket_encryption(
        Bucket="demo-app-data",
        ServerSideEncryptionConfiguration=_default_encryption("aws:kms"),
    )
    data.put_bucket_logging(
        Bucket="demo-app-data",
        BucketLoggingStatus={"LoggingEnabled": {"TargetBucket": "demo-access-logs", "TargetPrefix": "demo-app-data/"}},
    )
    planted.append("Bucket demo-app-data configured properly (should pass)")

    # --- EC2 / VPC -----------------------------------------------------------------------
    use1 = boto3.client("ec2", region_name="us-east-1")
    vpc = use1.describe_vpcs()["Vpcs"][0]["VpcId"]
    admin_sg = use1.create_security_group(GroupName="legacy-admin", Description="old jump box", VpcId=vpc)["GroupId"]
    use1.authorize_security_group_ingress(
        GroupId=admin_sg,
        IpPermissions=[
            {"IpProtocol": "tcp", "FromPort": 22, "ToPort": 22, "IpRanges": [{"CidrIp": "0.0.0.0/0"}]},
            {"IpProtocol": "tcp", "FromPort": 3389, "ToPort": 3389, "Ipv6Ranges": [{"CidrIpv6": "::/0"}]},
        ],
    )
    web_sg = use1.create_security_group(GroupName="web", Description="public https", VpcId=vpc)["GroupId"]
    use1.authorize_security_group_ingress(
        GroupId=web_sg,
        IpPermissions=[{"IpProtocol": "tcp", "FromPort": 443, "ToPort": 443, "IpRanges": [{"CidrIp": "0.0.0.0/0"}]}],
    )
    instance = use1.run_instances(
        ImageId="ami-12345678", MinCount=1, MaxCount=1, InstanceType="t3.micro", SecurityGroupIds=[admin_sg]
    )["Instances"][0]["InstanceId"]
    image = use1.create_image(InstanceId=instance, Name="demo-golden-image")["ImageId"]
    use1.modify_image_attribute(ImageId=image, LaunchPermission={"Add": [{"Group": "all"}]})
    volume = use1.create_volume(AvailabilityZone="us-east-1a", Size=8)["VolumeId"]
    use1.create_snapshot(VolumeId=volume, Description="private backup")
    planted.append("us-east-1: SSH open to 0.0.0.0/0 and RDP open to ::/0, an IMDSv1 instance, a public AMI")
    planted.append("us-east-1: EBS encryption by default left off; HTTPS-only security group (should pass)")

    euw2 = boto3.client("ec2", region_name="eu-west-2")
    euw2.enable_ebs_encryption_by_default()
    vpc2 = euw2.describe_vpcs()["Vpcs"][0]["VpcId"]
    db_sg = euw2.create_security_group(GroupName="reporting-db", Description="mysql", VpcId=vpc2)["GroupId"]
    euw2.authorize_security_group_ingress(
        GroupId=db_sg,
        IpPermissions=[{"IpProtocol": "tcp", "FromPort": 3306, "ToPort": 3306, "IpRanges": [{"CidrIp": "0.0.0.0/0"}]}],
    )
    euw2.run_instances(
        ImageId="ami-87654321",
        MinCount=1,
        MaxCount=1,
        InstanceType="t3.micro",
        SecurityGroupIds=[db_sg],
        MetadataOptions={"HttpTokens": "required"},
    )
    volume2 = euw2.create_volume(AvailabilityZone="eu-west-2a", Size=20)["VolumeId"]
    snapshot = euw2.create_snapshot(VolumeId=volume2, Description="db export")["SnapshotId"]
    euw2.modify_snapshot_attribute(
        SnapshotId=snapshot, Attribute="createVolumePermission", OperationType="add", GroupNames=["all"]
    )
    planted.append("eu-west-2: MySQL open to 0.0.0.0/0 and a public EBS snapshot; IMDSv2 instance (should pass)")

    # --- CloudTrail, KMS, RDS, GuardDuty, Config ---------------------------------------------
    _bucket("demo-trail-logs", "us-east-1")
    trail = boto3.client("cloudtrail", region_name="us-east-1")
    trail.create_trail(Name="app-trail", S3BucketName="demo-trail-logs")
    trail.start_logging(Name="app-trail")
    trail.create_trail(Name="org-audit", S3BucketName="demo-trail-logs", IsMultiRegionTrail=True)
    planted.append("Bucket demo-trail-logs for CloudTrail, left with default settings")
    planted.append("CloudTrail: a single-region trail without validation or KMS, and a multi-region trail not logging")

    boto3.client("kms", region_name="us-east-1").create_key(Description="demo app data key")
    kms2 = boto3.client("kms", region_name="eu-west-2")
    rotated = kms2.create_key(Description="demo exports key")["KeyMetadata"]["KeyId"]
    kms2.enable_key_rotation(KeyId=rotated)
    planted.append("KMS: one key without rotation (us-east-1), one with rotation (eu-west-2)")

    rds_common = {
        "Engine": "postgres",
        "DBInstanceClass": "db.t3.micro",
        "MasterUsername": "app",
        "MasterUserPassword": "demo-only-password",
        "AllocatedStorage": 20,
    }
    boto3.client("rds", region_name="eu-west-2").create_db_instance(
        DBInstanceIdentifier="orders-db", PubliclyAccessible=True, StorageEncrypted=False, **rds_common
    )
    boto3.client("rds", region_name="us-east-1").create_db_instance(
        DBInstanceIdentifier="billing-db", PubliclyAccessible=False, StorageEncrypted=True, **rds_common
    )
    planted.append("RDS: orders-db public and unencrypted (eu-west-2); billing-db private and encrypted")

    boto3.client("guardduty", region_name="eu-west-2").create_detector(Enable=True)
    config = boto3.client("config", region_name="eu-west-2")
    config.put_configuration_recorder(
        ConfigurationRecorder={
            "name": "default",
            "roleARN": f"arn:aws:iam::{MOCK_ACCOUNT_ID}:role/demo-config-recorder",
            "recordingGroup": {"allSupported": True, "includeGlobalResourceTypes": True},
        }
    )
    _bucket("demo-config-delivery", "eu-west-2")
    config.put_delivery_channel(DeliveryChannel={"name": "default", "s3BucketName": "demo-config-delivery"})
    planted.append("Bucket demo-config-delivery (London) for AWS Config, left with default settings")
    config.start_configuration_recorder(ConfigurationRecorderName="default")
    planted.append("GuardDuty and AWS Config switched on in eu-west-2 only")
    return planted


def demo_suppressions(today: date) -> str:
    expires = (today + timedelta(days=180)).isoformat()
    return (
        "suppressions:\n"
        "  - check: s3-versioning-and-logging\n"
        "    resource: arn:aws:s3:::demo-access-logs\n"
        "    reason: Target bucket for the other buckets' access logs; logging it into itself would loop.\n"
        f"    expires: {expires}\n"
    )


def scan_demo_account(workers: int = 4) -> tuple[ScanResult, set[tuple[str, str]], list[str]]:
    """Build the mock account, scan it and return (result, API operations used, what was planted)."""
    with mocked_aws():
        planted = build_misconfigured_account()
        ctx = ScanContext.from_session(boto3.Session(region_name="us-east-1"))
        checks = all_checks()
        result = run_scan(ctx, checks, list(DEMO_REGIONS), max_workers=workers)
        result.note = DEMO_NOTE
        accepted, warnings = parse_suppressions(demo_suppressions(date.today()), {c.id for c in checks}, date.today())
        result.warnings.extend(warnings)
        result.warnings.extend(apply_suppressions(result.findings, accepted, {c.id for c in checks}))
        return result, set(ctx.operations), planted


def write_demo_reports(result: ScanResult, planted: list[str], output_dir: Path) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "report.json": json_report.write,
        "report.html": html_report.write,
        "report.sarif": sarif.write,
        "report.csv": csv_report.write,
    }
    written = []
    for name, writer in paths.items():
        writer(result, output_dir / name)
        written.append(output_dir / name)

    recorder = Console(record=True, width=150, color_system=None, file=io.StringIO())
    console_output.render(result, recorder)
    (output_dir / "console.txt").write_text(recorder.export_text(), encoding="utf-8")
    written.append(output_dir / "console.txt")

    (output_dir / "planted.txt").write_text(
        "What 'aws-security-audit demo' creates in the moto mock account before scanning it:\n\n"
        + "\n".join(f"- {line}" for line in planted)
        + "\n",
        encoding="utf-8",
    )
    written.append(output_dir / "planted.txt")
    return written
